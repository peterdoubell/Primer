"""Write the module coverage report for learning sequences.

    python tools/learning_games_report.py          # rewrite docs/learning-games-coverage.md
    python tools/learning_games_report.py --check  # fail if the report is stale

For every curriculum module the report lists the learning objective, the
interaction types, how feedback is given, the transfer task, the activities the
module already had, and the review status of the content. It ends with the
content and review gaps that remain.
"""
import collections
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from primer.curriculum import Curriculum  # noqa: E402
from primer.learning_games import authoring, catalog  # noqa: E402

REPORT = ROOT / "docs" / "learning-games-coverage.md"
STAGES = ["0", "1", "2", "3", "4", "5"]
EXTRA_KINDS = ("model", "activity", "music", "reference", "practice")


def _cell(text: str, limit: int = 220) -> str:
    text = " ".join(str(text).split()).replace("|", "/")
    return text if len(text) <= limit else text[:limit - 1].rstrip() + "…"


def _status(seq) -> str:
    origin = seq["origin"]
    if origin["kind"] == "derived":
        return "derived from reviewed reference"
    if origin.get("reviewed"):
        return "reviewed %s" % origin["reviewed"]
    if origin.get("review_by"):
        return "awaiting %s review" % origin["review_by"]
    return "authored, awaiting subject review"


def _feedback(seq) -> str:
    steps = [b for b in seq["beats"] if b["kind"] == "step"]
    tags = set()
    anticipated = 0
    for step in steps:
        for option in step.get("options") or []:
            if not option["correct"] and option.get("error"):
                tags.add(option["error"])
                anticipated += 1
        for wrong in step.get("wrong") or []:
            tags.add(wrong.get("error", ""))
            anticipated += 1
    hints = sum(len(step.get("hints") or []) for step in steps)
    computed = sum(1 for step in steps if step["type"] in ("explore", "edit") or step.get("computed"))
    kinds = len(tags - {""})
    parts = ["%d anticipated error%s (%d kind%s)" % (anticipated, "" if anticipated == 1 else "s",
                                                     kinds, "" if kinds == 1 else "s"),
             "%d hint%s" % (hints, "" if hints == 1 else "s"), "Why on every step"]
    if computed:
        parts.append("%d worked by calculation" % computed)
    return "; ".join(parts)


def build(curr, cat) -> str:
    nodes = curr.nodes
    names = {d["id"]: d["name"] for d in curr.domains}
    order = {d["id"]: i for i, d in enumerate(curr.domains)}
    domains = collections.OrderedDict()
    for node_id, node in sorted(nodes.items(), key=lambda item: (order.get(item[1]["domain"], 99),
                                                                 item[1]["stage"], item[0])):
        domains.setdefault(node["domain"], []).append(node_id)
    covered = set(cat.covered())
    totals = collections.Counter()
    statuses = collections.Counter()
    sequences = 0
    steps_total = 0
    by_domain = []
    gaps_clinical, gaps_derived, low_variety = [], [], []
    for domain, ids in domains.items():
        count = sum(1 for node_id in ids if node_id in covered)
        by_domain.append((domain, len(ids), count))
        for node_id in ids:
            for seq in cat.sequences(node_id):
                sequences += 1
                statuses[_status(seq)] += 1
                types = [b["type"] for b in seq["beats"] if b["kind"] == "step"]
                steps_total += len(types)
                totals.update(types)
                if seq["origin"].get("review_by"):
                    gaps_clinical.append(node_id)
                elif seq["origin"]["kind"] == "derived":
                    gaps_derived.append(node_id)
                elif len(set(types)) == 2:
                    low_variety.append(node_id)

    out = []
    add = out.append
    add("# Learning sequences: module coverage report")
    add("")
    add("Generated by `python tools/learning_games_report.py` from `data/learning-games/*.lg` "
        "and the curriculum. Do not edit by hand; `--check` fails when this file is stale.")
    add("")
    add("Every module opens with a short interactive sequence that follows one loop: introduce the idea, "
        "demonstrate it, ask the reader to predict or act, check the response on the server, explain it, "
        "and finish with a transfer task in a fresh situation. Finishing a sequence records study "
        "(a small amount of growth, once); mastery is still earned only by the module quiz on spaced days.")
    add("")
    add("## Summary")
    add("")
    add("- Modules with a learning sequence: **%d of %d**" % (len(covered), len(nodes)))
    add("- Sequences: **%d**, checked steps: **%d**" % (sequences, steps_total))
    add("- Authoring problems: **%d**" % len(cat.problems))
    add("")
    add("| Domain | Modules | With a sequence |")
    add("|---|---:|---:|")
    for domain, total, count in by_domain:
        add("| %s | %d | %d |" % (names.get(domain, domain), total, count))
    add("")
    add("| Interaction type | Steps |")
    add("|---|---:|")
    for kind, number in totals.most_common():
        add("| %s | %d |" % (authoring.INTERACTION_LABELS.get(kind, kind), number))
    add("")
    add("| Review status | Sequences |")
    add("|---|---:|")
    for status, number in statuses.most_common():
        add("| %s | %d |" % (status, number))
    add("")
    add("## Remaining content and review gaps")
    add("")
    add("1. **No authored sequence has had subject review.** All %d authored sequences were written for "
        "Primer and validated mechanically (every step solvable, distractors tagged, hints and explanations "
        "present, explore targets reachable, no step repeating a quiz question). Each still needs a reviewer "
        "in its field before it is marked reviewed." % statuses["authored, awaiting subject review"])
    add("2. **%d clinical radiology sequences await a radiologist.** They were written from each module's own "
        "goal and question bank, without a reviewed reporting reference, and say so to the reader: %s." %
        (len(gaps_clinical), ", ".join("`%s`" % n for n in gaps_clinical)))
    add("3. **%d radiology sequences are derived** from each module's reviewed reporting reference. Their "
        "statements come from the reference; the question framing and distractors were generated and are "
        "not separately reviewed." % len(gaps_derived))
    add("4. **%d authored sequences use only two interaction types.** They meet the minimum; a reviewer may "
        "want a third kind of step." % len(low_variety))
    add("5. **Language Arcade is not on main.** It exists only as uncommitted work in a separate checkout, "
        "so it is not linked from any sequence. The language sequences here stand on their own.")
    add("6. **Explore models are deliberately simple.** Parameter explorers use stated, idealised formulas "
        "(for example a fixed sound speed or a single-energy attenuation law); each step's explanation names "
        "the simplification.")
    add("")
    add("## Modules")
    add("")
    add("Columns: the learning objective, the interaction types in order of first use, how feedback is "
        "given, the transfer task, what the module already offered beyond its lesson and quiz, and the "
        "review status.")
    for domain, ids in domains.items():
        add("")
        add("### %s" % names.get(domain, domain))
        add("")
        add("| Module | Stage | Objective | Interactions | Feedback | Transfer task | Already offered | Status |")
        add("|---|:-:|---|---|---|---|---|---|")
        for node_id in ids:
            node = nodes[node_id]
            seqs = cat.sequences(node_id)
            if not seqs:
                add("| `%s` %s | %s | — | — | — | — | — | **no sequence** |" % (node_id, _cell(node["title"], 60), node["stage"]))
                continue
            extras = [a["label"] for a in cat.existing_activities(node) if a["kind"] in EXTRA_KINDS]
            for seq in seqs:
                steps = [b for b in seq["beats"] if b["kind"] == "step"]
                kinds = []
                for step in steps:
                    label = authoring.INTERACTION_LABELS.get(step["type"], step["type"])
                    if label not in kinds:
                        kinds.append(label)
                transfer = next((s["prompt"] for s in steps if s.get("transfer")), "—")
                title = node["title"] if len(seqs) == 1 else "%s: %s" % (node["title"], seq["title"])
                add("| `%s` %s | %s | %s | %s | %s | %s | %s | %s |" % (
                    node_id, _cell(title, 80), node["stage"], _cell(seq["objective"]), ", ".join(kinds),
                    _feedback(seq), _cell(transfer, 180), _cell("; ".join(extras) or "lesson and quiz only", 160),
                    _status(seq)))
    add("")
    return "\n".join(out)


def main(argv):
    curr = Curriculum()
    cat = catalog.Catalog(curr.nodes)
    if cat.problems:
        for problem in cat.problems:
            print("!", problem)
        print("%d authoring problem(s): fix them before writing the report" % len(cat.problems))
        return 1
    text = build(curr, cat)
    if "--check" in argv:
        current = REPORT.read_text(encoding="utf-8") if REPORT.exists() else ""
        if current != text:
            print("%s is stale: run python tools/learning_games_report.py" % REPORT.relative_to(ROOT))
            return 1
        print("coverage report up to date")
        return 0
    REPORT.write_text(text, encoding="utf-8")
    print("wrote %s" % REPORT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
